// bun scripts/analytics-inventory.ts [--data DIR] [--write]
//
// Prints what Blackbook collects, from the code and the database, not from memory:
//  - every event type the log accepts (server/validate.ts), its declared payload fields
//    (src/types/session.ts), the payload fields actually present in your data, and how many events
//    of that type exist;
//  - whether each type is documented in docs/telemetry.md and whether any non-test source file logs it;
//  - the derived metrics the analytics summaries compute (field names of the summary types).
// --write saves the output to docs/analytics-inventory.md.

import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { EVENT_TYPES } from '../server/validate';
import { openSqlite } from '../server/sqlBun';
import { SqliteUserStore } from '../server/userDb';

const args = process.argv.slice(2);
const dataDir = resolve(args.includes('--data') ? (args[args.indexOf('--data') + 1] ?? '') : join('data', 'app'));
const write = args.includes('--write');

const read = (p: string) => readFileSync(p, 'utf8');

// ---- declared payloads ----
const declared = new Map<string, string>();
{
  const src = read('src/types/session.ts');
  const block = src.slice(src.indexOf('export interface EventPayloads'), src.indexOf('export type EventType'));
  for (const m of block.matchAll(/^\s+(\w+): (Record<.*>|\{.*\});$/gm)) declared.set(m[1] as string, (m[2] as string).replace(/\s+/g, ' '));
}

// ---- observed data ----
const users = new SqliteUserStore(openSqlite(join(dataDir, 'user.db')));
const events = await users.listEvents();
const counts = new Map<string, number>();
const observed = new Map<string, Set<string>>();
for (const e of events) {
  counts.set(e.type, (counts.get(e.type) ?? 0) + 1);
  const keys = observed.get(e.type) ?? new Set<string>();
  for (const k of Object.keys(e.payload)) keys.add(k);
  observed.set(e.type, keys);
}

// ---- documented ----
const doc = read('docs/telemetry.md');
const documented = new Set<string>();
for (const line of doc.split('\n')) {
  if (!line.startsWith('|')) continue;
  for (const m of line.split('|')[1]?.matchAll(/`(\w+)`/g) ?? []) documented.add(m[1] as string);
}

// ---- logged in code ----
function sources(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) sources(p, out);
    else if (/\.(ts|tsx)$/.test(name) && !/\.test\.tsx?$/.test(name)) out.push(p);
  }
  return out;
}
const files = [...sources('src'), ...sources('server')].filter((f) => !f.endsWith(join('types', 'session.ts')) && !f.endsWith('validate.ts'));
const text = files.map(read).join('\n');
const loggedInCode = (type: string) => new RegExp(`['"\`]${type}['"\`]`).test(text);

// ---- derived metrics ----
function interfaceFields(file: string, name: string): string[] {
  const src = read(file);
  const start = src.indexOf(`export interface ${name}`);
  if (start < 0) return [];
  const end = src.indexOf('\n}', start);
  return [...src.slice(start, end).matchAll(/^\s{2}(\w+)\??:/gm)].map((m) => m[1] as string);
}
const SUMMARIES = ['OverviewSummary', 'SkillRow', 'SkillDetail', 'TimingBaseline', 'FlaggedQuestion', 'ModulePacing', 'TimingSummary', 'BehaviorCounts', 'BehaviorSummary', 'TestHistoryRow'];

const types = Object.keys(EVENT_TYPES).sort();
const lines: string[] = [];
lines.push('# Analytics inventory');
lines.push('');
lines.push('Generated by `bun scripts/analytics-inventory.ts --write` from the code and the local database. Do not edit by hand; rerun the script. It lists what is collected, not what any screen shows.');
lines.push('');
lines.push(`Events in the local database: ${events.length}. Event types the log accepts: ${types.length}.`);
lines.push('');
lines.push('## Events');
lines.push('');
lines.push('| Type | Declared payload | Fields seen in your data | Events | In docs/telemetry.md | Logged by code |');
lines.push('|---|---|---|---|---|---|');
const notLogged: string[] = [];
const notDocumented: string[] = [];
for (const t of types) {
  const seen = [...(observed.get(t) ?? [])].sort().join(', ') || '-';
  const logged = loggedInCode(t);
  if (!logged) notLogged.push(t);
  if (!documented.has(t)) notDocumented.push(t);
  lines.push(`| \`${t}\` | \`${declared.get(t) ?? '?'}\` | ${seen} | ${counts.get(t) ?? 0} | ${documented.has(t) ? 'yes' : 'NO'} | ${logged ? 'yes' : 'NO'} |`);
}
lines.push('');
lines.push('## Gaps');
lines.push('');
lines.push(notLogged.length === 0 ? '- Every accepted event type is logged by some non-test source file.' : `- Accepted but no source file logs them: ${notLogged.map((t) => `\`${t}\``).join(', ')}.`);
lines.push(notDocumented.length === 0 ? '- Every accepted event type appears in docs/telemetry.md.' : `- Accepted but not in docs/telemetry.md: ${notDocumented.map((t) => `\`${t}\``).join(', ')}.`);
const documentedOnly = [...documented].filter((t) => isEventLike(t) && !(t in EVENT_TYPES) && t !== 'session_id' && t !== 'question_id');
function isEventLike(t: string): boolean {
  return /^(session|question|choice|strike|spr|flag|nav|finish|tab|window|idle|confidence|report|rationale|timer|five|exam|reference|navigator|test|mistake)_/.test(t);
}
lines.push(documentedOnly.length === 0 ? '- Nothing in docs/telemetry.md names an event the log does not accept.' : `- Documented but not an accepted event type: ${documentedOnly.map((t) => `\`${t}\``).join(', ')}.`);
const never = types.filter((t) => (counts.get(t) ?? 0) === 0);
lines.push(`- Accepted types with no events in your data yet: ${never.length === 0 ? 'none' : never.map((t) => `\`${t}\``).join(', ')}. (Expected for features you have not used.)`);
const metricsFile = 'src/services/telemetry/metrics.ts';
lines.push(existsSync(metricsFile) ? `- \`${metricsFile}\` exists.` : `- docs/telemetry.md describes per-question derived metrics in \`${metricsFile}\`, but that file does not exist. The per-question and per-session figures listed there (wall time, idle time, swaps and so on) are computed only inside the analytics summaries below, not by a module of that name.`);
lines.push('');
lines.push('## Other stored data');
lines.push('');
lines.push('- `sessions`: one JSON record per drill, Browse single, retry, exam module and test container (config, queue, per-question progress with active time, visits, changes, strikes, flags, confidence).');
lines.push('- `attempts`: one row per question per session (response, correct, time, first-visit time, changes, confidence).');
lines.push('- `flags`: the cross-session "flag for later" list.');
lines.push('- `mistake_tags`: why a question was missed (reason, optional note, whether the suggestion was accepted). Append-only; the note stays here and never goes into an event.');
lines.push('- The question bank is not user data and is not collected.');
lines.push('');
lines.push('## Derived metrics currently computed');
lines.push('');
lines.push('Field names of the summary types in `src/types/analytics.ts`, which `server/analytics.ts` fills (and `src/services/analytics/brute.ts` recomputes independently as a check).');
lines.push('');
for (const name of SUMMARIES) {
  const f = interfaceFields('src/types/analytics.ts', name);
  if (f.length > 0) lines.push(`- **${name}**: ${f.join(', ')}`);
}
lines.push('');
lines.push('Thresholds and parameters live in `src/config/analyticsConfig.ts` and `src/config/mistakeConfig.ts`. Definitions: `docs/analytics.md`.');
lines.push('');

const out = lines.join('\n');
console.log(out);
if (write) {
  writeFileSync('docs/analytics-inventory.md', out, 'utf8');
  console.error('Wrote docs/analytics-inventory.md');
}
